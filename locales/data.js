// A lesson is shown as stage + subject ("小学语文"), and core stores exactly that
// on the activity record, so every combination is a key of its own:
// 小学校のこくご · Reading (Primary school).
const STAGE_KEYS = ['小学', '大学', '研究生']
const SUBJECT_KEYS = ['语文', '数学', '政治', '美术', '音乐', '礼仪', '体育', '武术', '劳动']
for (const stage of STAGE_KEYS) {
  for (const subject of SUBJECT_KEYS) {
    ja[stage + subject] = `${ja[stage]}の${ja[subject]}`
    en[stage + subject] = `${en[subject]} (${en[stage]})`
  }
}

export default { ja, en }
